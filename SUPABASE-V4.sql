-- =========================================================
-- 5) SERVER-SIDE ORDER CREATION
-- Customer sends only product ID + username + optional promo.
-- Price and Robux are read from the admin-controlled products table.
-- =========================================================
drop function if exists public.create_public_order(bigint,text,text);
create or replace function public.create_public_order(p_product_id bigint,p_roblox_username text,p_promo_code text default null)
returns table(order_code text, robux_amount integer, price bigint, promo_code text)
language plpgsql security definer set search_path=public
as $$
declare
  p public.products%rowtype;
  st integer;
  final_price bigint;
  promo_discount numeric := 0;
  normalized_code text;
  new_code text;
  chars text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  i integer;
begin
  if length(trim(p_roblox_username)) < 2 or length(trim(p_roblox_username)) > 30 then
    raise exception 'Username Roblox tidak valid.';
  end if;
  select * into p from public.products where id=p_product_id and active=true limit 1;
  if not found then raise exception 'Paket Robux tidak tersedia.'; end if;
  select stock into st from public.store_settings where id=1;
  if coalesce(st,0) < p.robux then raise exception 'Stok Robux tidak cukup.'; end if;
  normalized_code=upper(trim(coalesce(p_promo_code,'')));
  if normalized_code <> '' then
    select discount_percent into promo_discount from public.promos where upper(code)=normalized_code and active=true and now() between starts_at and expires_at limit 1;
    if promo_discount is null then raise exception 'Kode promo tidak valid atau sudah kedaluwarsa.'; end if;
  else
    normalized_code=null;
  end if;
  final_price=round(p.price*(1-(promo_discount/100)))::bigint;
  loop
    new_code='LP-'||to_char(now(),'YYYYMMDD')||'-';
    for i in 1..5 loop new_code=new_code||substr(chars,1+floor(random()*length(chars))::int,1); end loop;
    begin
      insert into public.orders(order_code,roblox_username,robux_amount,price,promo_code,status)
      values(new_code,trim(p_roblox_username),p.robux,final_price,normalized_code,'pending');
      exit;
    exception when unique_violation then
    end;
  end loop;
  return query select new_code,p.robux,final_price,normalized_code;
end; $$;
revoke all on function public.create_public_order(bigint,text,text) from public;
grant execute on function public.create_public_order(bigint,text,text) to anon, authenticated;

-- =========================================================
-- 6) PUBLIC ORDER STATUS
-- =========================================================
drop function if exists public.get_public_order_status(text);
create or replace function public.get_public_order_status(p_order_code text)
returns table(order_code text,roblox_username text,robux_amount integer,price bigint,promo_code text,status text,created_at timestamptz)
language sql security definer set search_path=public
as $$
  select o.order_code,o.roblox_username,o.robux_amount,o.price,o.promo_code,o.status,o.created_at
  from public.orders o where upper(o.order_code)=upper(trim(p_order_code)) limit 1;
$$;
revoke all on function public.get_public_order_status(text) from public;
grant execute on function public.get_public_order_status(text) to anon, authenticated;

-- =========================================================
-- 7) RATING SUBMISSION: only completed orders, one rating/order
-- =========================================================
drop function if exists public.submit_order_rating(text,text,text,integer,text);
create or replace function public.submit_order_rating(p_order_code text,p_name text,p_product text,p_rating integer,p_review text)
returns json
language plpgsql security definer set search_path=public
as $$
declare st text; normalized text; result json;
begin
  normalized=upper(trim(p_order_code));
  select status into st from public.orders where upper(order_code)=normalized limit 1;
  if st is null then raise exception 'Order ID tidak ditemukan.'; end if;
  if st <> 'completed' then raise exception 'Rating hanya bisa diberikan setelah order berstatus selesai.'; end if;
  if exists(select 1 from public.order_ratings where upper(order_code)=normalized) then raise exception 'Order ini sudah pernah memberikan rating.'; end if;
  insert into public.order_ratings(order_code,name,product,rating,review,approved)
  values(normalized,trim(p_name),trim(p_product),p_rating,trim(p_review),false)
  returning json_build_object('id',id,'order_code',order_code) into result;
  return result;
end; $$;
revoke all on function public.submit_order_rating(text,text,text,integer,text) from public;
grant execute on function public.submit_order_rating(text,text,text,integer,text) to anon, authenticated;


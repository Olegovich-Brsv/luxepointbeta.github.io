-- Luxe Point V4
-- Dynamic stock + Robux/price packages + order-code rating + promo + public order tracking.

-- =========================================================
-- 1) PROMOS
-- =========================================================
create table if not exists public.promos (
  id bigint generated by default as identity primary key,
  code text unique not null,
  discount_percent numeric(5,2) not null check (discount_percent >= 0 and discount_percent <= 100),
  starts_at timestamptz not null,
  expires_at timestamptz not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (expires_at > starts_at)
);
alter table public.promos enable row level security;
drop policy if exists "public can read active promos" on public.promos;
create policy "public can read active promos" on public.promos for select to anon, authenticated using (active=true and now()>=starts_at and now()<=expires_at);
drop policy if exists "admins can read promos" on public.promos;
create policy "admins can read promos" on public.promos for select to authenticated using (exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "admins can insert promos" on public.promos;
create policy "admins can insert promos" on public.promos for insert to authenticated with check (exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "admins can update promos" on public.promos;
create policy "admins can update promos" on public.promos for update to authenticated using (exists(select 1 from public.admin_users a where a.user_id=auth.uid())) with check (exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "admins can delete promos" on public.promos;
create policy "admins can delete promos" on public.promos for delete to authenticated using (exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
grant select on public.promos to anon;
grant select, insert, update, delete on public.promos to authenticated;

